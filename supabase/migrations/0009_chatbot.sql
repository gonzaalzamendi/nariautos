-- Fuente de datos del chatbot: preguntas frecuentes y un único JSON con la información pública de NariAutos.

create table if not exists preguntas_frecuentes (
  id int generated by default as identity primary key,
  pregunta text not null unique,
  respuesta text not null,
  activa boolean not null default true,
  orden int not null default 0,
  creado_en timestamptz not null default now()
);
alter table preguntas_frecuentes enable row level security;
revoke all on preguntas_frecuentes from anon, authenticated;
grant select, insert, update, delete on preguntas_frecuentes to anon;
-- Lectura pública solo de las activas; escritura solo del servidor
create policy lectura on preguntas_frecuentes for select to anon using (activa or (select private.es_servidor()));
create policy servidor_alta on preguntas_frecuentes for insert to anon with check ((select private.es_servidor()));
create policy servidor_cambio on preguntas_frecuentes for update to anon using ((select private.es_servidor())) with check ((select private.es_servidor()));
create policy servidor_baja on preguntas_frecuentes for delete to anon using ((select private.es_servidor()));
grant usage on all sequences in schema public to anon;

-- Todo el contexto en una sola llamada: POST /rest/v1/rpc/chatbot_contexto con la clave pública.
-- SECURITY INVOKER: solo ve lo que RLS ya permite al rol anónimo. Las columnas se eligen una por una:
-- no hay datos de clientes, empleados, ventas ni costos.
create or replace function chatbot_contexto() returns jsonb
language sql stable security invoker set search_path = public as $$
  select jsonb_build_object(
    'generado_en', to_char(now() at time zone 'America/Argentina/Buenos_Aires', 'YYYY-MM-DD HH24:MI'),
    'unidades', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', u.id, 'marca', u.marca, 'modelo', u.modelo, 'version', u.version, 'anio', u.anio, 'km', u.km,
        'condicion', u.condicion, 'precio', u.precio, 'combustible', u.combustible, 'transmision', u.transmision,
        'color', u.color, 'sucursal', s.nombre, 'localidad', s.localidad, 'ficha', '/catalogo/' || u.id) order by u.marca, u.modelo, u.precio)
      from unidades u join sucursales s on s.id = u.sucursal_id where u.estado = 'disponible'), '[]'::jsonb),
    'sucursales', coalesce((
      select jsonb_agg(jsonb_build_object(
        'nombre', s.nombre, 'direccion', s.direccion, 'localidad', s.localidad, 'telefono', s.telefono,
        'horario_ventas', s.horario_atencion, 'tiene_taller', s.tiene_taller,
        'horario_taller', case when s.tiene_taller then 'Lunes a viernes de ' || to_char(s.taller_abre, 'HH24:MI') || ' a ' || to_char(s.taller_cierra, 'HH24:MI') end,
        'deriva_turnos_a', r.nombre, 'km_al_taller', s.km_a_referencia) order by s.id)
      from sucursales s left join sucursales r on r.id = s.taller_referencia_id where s.activa), '[]'::jsonb),
    'servicios_taller', coalesce((
      select jsonb_agg(jsonb_build_object('nombre', v.nombre, 'descripcion', v.descripcion, 'duracion_min', v.duracion_min,
        'precio_orientativo', nullif(v.precio_orientativo, 0)) order by v.id)
      from servicios v where v.activo), '[]'::jsonb),
    'promociones', coalesce((
      select jsonb_agg(jsonb_build_object('titulo', p.titulo, 'descripcion', p.descripcion, 'vigente_desde', p.vigente_desde,
        'vigente_hasta', p.vigente_hasta, 'alcance', coalesce(s.nombre, 'Toda la red'),
        'unidades', coalesce((select jsonb_agg(u.marca || ' ' || u.modelo || coalesce(' ' || u.version, '') order by u.marca, u.modelo)
                              from promocion_unidad pu join unidades u on u.id = pu.unidad_id where pu.promocion_id = p.id and u.estado = 'disponible'), '[]'::jsonb)) order by p.vigente_hasta)
      from promociones p left join sucursales s on s.id = p.sucursal_id
      where p.activa and current_date between p.vigente_desde and p.vigente_hasta), '[]'::jsonb),
    'preguntas_frecuentes', coalesce((
      select jsonb_agg(jsonb_build_object('pregunta', f.pregunta, 'respuesta', f.respuesta) order by f.orden, f.id)
      from preguntas_frecuentes f where f.activa), '[]'::jsonb));
$$;
revoke execute on function chatbot_contexto() from public, authenticated;
grant execute on function chatbot_contexto() to anon;
