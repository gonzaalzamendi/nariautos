-- 5) Código de vehículo (2 letras + 2 dígitos), único: es la llave del cliente para ver el historial
create or replace function generar_codigo_auto() returns text language plpgsql set search_path = public as $$
declare v text; abc constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ';
begin
  loop
    v := substr(abc, 1 + floor(random() * 24)::int, 1) || substr(abc, 1 + floor(random() * 24)::int, 1) || lpad(floor(random() * 100)::int::text, 2, '0');
    exit when not exists (select 1 from vehiculos where codigo_auto = v);
  end loop;
  return v;
end $$;
alter table vehiculos add column if not exists codigo_auto text;
do $$ declare r record; begin
  for r in select id from vehiculos where codigo_auto is null loop update vehiculos set codigo_auto = generar_codigo_auto() where id = r.id; end loop;
end $$;
alter table vehiculos alter column codigo_auto set not null;
alter table vehiculos add constraint vehiculos_codigo_auto_formato check (codigo_auto ~ '^[A-Z]{2}[0-9]{2}$');
create unique index if not exists vehiculos_codigo_auto_idx on vehiculos(codigo_auto);
create or replace function asignar_codigo_auto() returns trigger language plpgsql set search_path = public as $$
begin
  if new.codigo_auto is null then new.codigo_auto := generar_codigo_auto(); end if;
  return new;
end $$;
create trigger vehiculos_codigo before insert on vehiculos for each row execute function asignar_codigo_auto();

-- 6) Repuestos del taller
create table repuestos (
  id int generated by default as identity primary key,
  sucursal_id int not null references sucursales(id),
  codigo text not null, nombre text not null,
  stock int not null default 0 check (stock >= 0),
  stock_minimo int not null default 0 check (stock_minimo >= 0),
  precio numeric(12,2) not null default 0 check (precio >= 0),
  activo boolean not null default true,
  unique (sucursal_id, codigo)
);
create table repuestos_orden (
  id int generated by default as identity primary key,
  orden_id int not null references ordenes_trabajo(id) on delete cascade,
  repuesto_id int not null references repuestos(id),
  cantidad int not null check (cantidad > 0),
  creado_en timestamptz not null default now()
);
create index repuestos_orden_orden_idx on repuestos_orden(orden_id);
create index repuestos_orden_repuesto_idx on repuestos_orden(repuesto_id);
alter table repuestos enable row level security;
alter table repuestos_orden enable row level security;
revoke all on repuestos, repuestos_orden from anon, authenticated;
grant select, insert, update, delete on repuestos, repuestos_orden to anon;
create policy servidor on repuestos for all to anon using ((select private.es_servidor())) with check ((select private.es_servidor()));
create policy servidor on repuestos_orden for all to anon using ((select private.es_servidor())) with check ((select private.es_servidor()));
grant usage on all sequences in schema public to anon;

-- Descuenta stock con bloqueo de fila: nunca queda negativo
create or replace function usar_repuesto(p_orden int, p_repuesto int, p_cantidad int) returns void language plpgsql set search_path = public as $$
declare r repuestos;
begin
  select * into r from repuestos where id = p_repuesto for update;
  if r.id is null or not r.activo then raise exception 'NARI: Ese repuesto no está disponible.'; end if;
  if r.stock < p_cantidad then raise exception 'NARI: Stock insuficiente de %: quedan % y pediste %.', r.nombre, r.stock, p_cantidad; end if;
  update repuestos set stock = stock - p_cantidad where id = p_repuesto;
  insert into repuestos_orden (orden_id, repuesto_id, cantidad) values (p_orden, p_repuesto, p_cantidad);
end $$;

-- 7) PIN: informa si está vencido; acceso por nombre de usuario
create or replace function verificar_pin(p_empleado int, p_pin text, p_ip text default null)
returns jsonb language plpgsql set search_path = public, extensions as $$
declare e empleados;
begin
  select * into e from empleados where id = p_empleado and activo for update;
  if e.id is null then return jsonb_build_object('ok', false, 'motivo', 'invalido'); end if;
  if e.bloqueado_hasta is not null and e.bloqueado_hasta > now() then
    return jsonb_build_object('ok', false, 'motivo', 'bloqueado', 'hasta', e.bloqueado_hasta);
  end if;
  if e.pin_hash = crypt(p_pin, e.pin_hash) then
    update empleados set intentos_fallidos = 0, bloqueado_hasta = null where id = e.id;
    insert into intentos_acceso (empleado_id, exitoso, ip) values (e.id, true, p_ip);
    return jsonb_build_object('ok', true, 'id', e.id, 'nombre', e.nombre, 'rol', e.rol, 'sucursal_id', e.sucursal_id,
      'pin_vencido', e.rol <> 'gerencia' and e.pin_cambiado_en < now() - interval '3 months');
  end if;
  insert into intentos_acceso (empleado_id, exitoso, ip) values (e.id, false, p_ip);
  if e.intentos_fallidos + 1 >= 5 then
    update empleados set intentos_fallidos = 0, bloqueado_hasta = now() + interval '5 minutes' where id = e.id;
    return jsonb_build_object('ok', false, 'motivo', 'bloqueado', 'hasta', now() + interval '5 minutes');
  end if;
  update empleados set intentos_fallidos = intentos_fallidos + 1 where id = e.id;
  return jsonb_build_object('ok', false, 'motivo', 'pin', 'restantes', 5 - (e.intentos_fallidos + 1));
end $$;

create or replace function verificar_acceso(p_usuario text, p_pin text, p_ip text default null)
returns jsonb language plpgsql set search_path = public as $$
declare v_id int;
begin
  select id into v_id from empleados where usuario = lower(trim(p_usuario)) and activo;
  if v_id is null then return jsonb_build_object('ok', false, 'motivo', 'invalido'); end if;
  return verificar_pin(v_id, p_pin, p_ip);
end $$;

-- 8) Turnos: una patente siempre corresponde al mismo vehículo (marca, modelo y año);
--    el cliente se identifica por teléfono + nombre (los teléfonos pueden repetirse)
create or replace function reservar_turno(
  p_servicio int, p_taller int, p_origen int, p_canal text, p_fecha date, p_hora time,
  p_patente text, p_marca text, p_modelo text, p_anio int, p_km int,
  p_nombre text, p_telefono text, p_email text default null,
  p_observaciones text default null, p_empleado int default null)
returns turnos language plpgsql set search_path = public as $$
declare v_srv servicios; v_cliente int; v vehiculos; v_turno turnos;
begin
  select * into v_srv from servicios where id = p_servicio and activo;
  if v_srv.id is null then raise exception 'NARI: El servicio elegido no está disponible.'; end if;
  if v_srv.requiere_descripcion and coalesce(length(trim(p_observaciones)), 0) < 10 then
    raise exception 'NARI: Para «%» describí brevemente el problema (al menos 10 caracteres).', v_srv.nombre;
  end if;
  select * into v from vehiculos where patente = upper(p_patente);
  if v.id is not null and (lower(trim(v.marca)) <> lower(trim(p_marca)) or lower(trim(v.modelo)) <> lower(trim(p_modelo)) or v.anio is distinct from p_anio) then
    raise exception 'NARI: La patente % ya está registrada como % % %. Revisá la patente o usá esos datos del vehículo.', v.patente, v.marca, v.modelo, v.anio;
  end if;
  perform verificar_cupo(p_taller, p_fecha, p_hora, v_srv.duracion_min);

  select id into v_cliente from clientes where telefono = p_telefono and lower(trim(nombre)) = lower(trim(p_nombre)) order by id limit 1;
  if v_cliente is null then
    insert into clientes (nombre, telefono, email) values (trim(p_nombre), p_telefono, nullif(p_email, '')) returning id into v_cliente;
  elsif nullif(p_email, '') is not null then
    update clientes set email = p_email where id = v_cliente;
  end if;

  if v.id is null then
    insert into vehiculos (patente, marca, modelo, anio, km_actual, cliente_id)
    values (upper(p_patente), trim(p_marca), trim(p_modelo), p_anio, p_km, v_cliente) returning * into v;
  else
    update vehiculos set km_actual = greatest(coalesce(km_actual, 0), p_km), cliente_id = v_cliente where id = v.id;
  end if;

  insert into turnos (codigo, servicio_id, vehiculo_id, cliente_id, sucursal_origen_id, sucursal_taller_id, canal_origen, fecha, hora, duracion_min, observaciones, creado_por)
  values (generar_codigo_turno(), p_servicio, v.id, v_cliente, p_origen, p_taller, p_canal, p_fecha, p_hora, v_srv.duracion_min, nullif(trim(p_observaciones), ''), p_empleado)
  returning * into v_turno;
  insert into eventos_turno (turno_id, estado, detalle, empleado_id)
  values (v_turno.id, 'solicitado', case when v_turno.derivado then 'Turno derivado desde otra sucursal' else 'Turno solicitado' end, p_empleado);
  return v_turno;
end $$;

