-- Esquema principal de NariAutos

create table sucursales (
  id int generated by default as identity primary key,
  nombre text not null unique,
  direccion text not null,
  localidad text not null,
  telefono text not null,
  email text,
  horario_atencion text not null,
  lat numeric(9,6), lng numeric(9,6),
  tiene_taller boolean not null default false,
  capacidad_boxes int,
  taller_abre time, taller_cierra time,
  taller_referencia_id int references sucursales(id),
  km_a_referencia numeric(5,1),
  activa boolean not null default true,
  constraint taller_completo check (
    (tiene_taller and capacidad_boxes > 0 and taller_abre is not null and taller_cierra is not null and taller_abre < taller_cierra and taller_referencia_id is null)
    or (not tiene_taller and capacidad_boxes is null and taller_referencia_id is not null and taller_referencia_id <> id))
);

create table empleados (
  id int generated by default as identity primary key,
  nombre text not null,
  rol text not null check (rol in ('vendedor','asesor','jefe_taller','gerencia')),
  sucursal_id int references sucursales(id),
  pin_hash text not null,
  activo boolean not null default true,
  intentos_fallidos int not null default 0,
  bloqueado_hasta timestamptz,
  creado_en timestamptz not null default now(),
  constraint sucursal_segun_rol check (rol = 'gerencia' or sucursal_id is not null)
);

create table mecanicos (
  id int generated by default as identity primary key,
  nombre text not null,
  sucursal_id int not null references sucursales(id),
  especialidad text,
  activo boolean not null default true
);

create table clientes (
  id int generated by default as identity primary key,
  nombre text not null,
  telefono text not null,
  email text,
  creado_en timestamptz not null default now()
);
create index clientes_telefono_idx on clientes(telefono);

create table vehiculos (
  id int generated by default as identity primary key,
  patente text not null unique check (patente = upper(patente) and patente ~ '^[A-Z0-9]{6,7}$'),
  marca text not null, modelo text not null,
  anio int check (anio between 1950 and 2100),
  km_actual int check (km_actual >= 0),
  cliente_id int references clientes(id)
);
create index vehiculos_cliente_idx on vehiculos(cliente_id);

create table unidades (
  id int generated by default as identity primary key,
  sucursal_id int not null references sucursales(id),
  marca text not null, modelo text not null, version text,
  anio int not null check (anio between 1950 and 2100),
  km int not null default 0 check (km >= 0),
  condicion text not null check (condicion in ('0km','usado')),
  precio numeric(14,2) not null check (precio > 0),
  combustible text not null check (combustible in ('nafta','diesel','hibrido','electrico','gnc')),
  transmision text not null check (transmision in ('manual','automatica')),
  color text, descripcion text,
  estado text not null default 'disponible' check (estado in ('disponible','reservada','vendida')),
  fecha_ingreso date not null default current_date,
  fecha_venta date, precio_venta numeric(14,2),
  vendedor_id int references empleados(id),
  creado_en timestamptz not null default now()
);
create index unidades_sucursal_idx on unidades(sucursal_id);
create index unidades_estado_idx on unidades(estado);
create index unidades_marca_modelo_idx on unidades(marca, modelo);
create index unidades_vendedor_idx on unidades(vendedor_id);

create table fotos_unidad (
  id int generated by default as identity primary key,
  unidad_id int not null references unidades(id) on delete cascade,
  url text, datos text, mime text,
  orden int not null default 0,
  constraint foto_con_contenido check (url is not null or datos is not null)
);
create index fotos_unidad_idx on fotos_unidad(unidad_id, orden);

create table promociones (
  id int generated by default as identity primary key,
  sucursal_id int references sucursales(id), -- null = toda la red
  titulo text not null, descripcion text not null,
  vigente_desde date not null, vigente_hasta date not null,
  activa boolean not null default true,
  creado_en timestamptz not null default now(),
  check (vigente_desde <= vigente_hasta)
);
create index promociones_sucursal_idx on promociones(sucursal_id);

create table promocion_unidad (
  promocion_id int not null references promociones(id) on delete cascade,
  unidad_id int not null references unidades(id) on delete cascade,
  primary key (promocion_id, unidad_id)
);
create index promocion_unidad_unidad_idx on promocion_unidad(unidad_id);

create table consultas (
  id int generated by default as identity primary key,
  tipo text not null check (tipo in ('cotizacion','test_drive','general')),
  canal text not null check (canal in ('web','telefono','whatsapp','redes','presencial')),
  estado text not null default 'nueva' check (estado in ('nueva','en_seguimiento','cotizada','test_drive_agendado','ganada','perdida')),
  motivo_perdida text,
  sucursal_id int not null references sucursales(id),
  vendedor_id int references empleados(id),
  unidad_id int references unidades(id) on delete set null,
  cliente_id int not null references clientes(id),
  mensaje text,
  simulacion jsonb,            -- simulación de financiación adjunta por el cliente
  precio_cotizado numeric(14,2), bonificacion numeric(14,2), financiacion_ofrecida text, cotizada_en timestamptz,
  creado_en timestamptz not null default now(),
  primera_respuesta_en timestamptz,
  cerrada_en timestamptz,
  check (estado <> 'perdida' or motivo_perdida is not null)
);
create index consultas_sucursal_estado_idx on consultas(sucursal_id, estado);
create index consultas_vendedor_idx on consultas(vendedor_id);
create index consultas_unidad_idx on consultas(unidad_id);
create index consultas_cliente_idx on consultas(cliente_id);

create table seguimientos_consulta (
  id int generated by default as identity primary key,
  consulta_id int not null references consultas(id) on delete cascade,
  empleado_id int references empleados(id),
  nota text not null,
  creado_en timestamptz not null default now()
);
create index seguimientos_consulta_idx on seguimientos_consulta(consulta_id);
create index seguimientos_empleado_idx on seguimientos_consulta(empleado_id);

create table test_drives (
  id int generated by default as identity primary key,
  consulta_id int not null references consultas(id) on delete cascade,
  unidad_id int references unidades(id) on delete set null,
  fecha date not null,
  franja text not null check (franja in ('manana','mediodia','tarde')),
  estado text not null default 'pendiente' check (estado in ('pendiente','confirmado','realizado','cancelado'))
);
create index test_drives_consulta_idx on test_drives(consulta_id);
create index test_drives_unidad_idx on test_drives(unidad_id);

create table servicios (
  id int generated by default as identity primary key,
  nombre text not null unique, descripcion text,
  duracion_min int not null check (duracion_min > 0 and duracion_min % 30 = 0),
  precio_orientativo numeric(12,2),
  activo boolean not null default true
);

create table turnos (
  id int generated by default as identity primary key,
  codigo text not null unique,
  servicio_id int not null references servicios(id),
  vehiculo_id int not null references vehiculos(id),
  cliente_id int not null references clientes(id),
  sucursal_origen_id int not null references sucursales(id),
  sucursal_taller_id int not null references sucursales(id),
  canal_origen text not null check (canal_origen in ('web','presencial','telefono','whatsapp','redes')),
  derivado boolean generated always as (sucursal_origen_id <> sucursal_taller_id) stored,
  fecha date not null, hora time not null,
  duracion_min int not null check (duracion_min > 0),
  estado text not null default 'solicitado' check (estado in ('solicitado','confirmado','recibido','en_reparacion','listo','entregado','cancelado','rechazado','ausente')),
  observaciones text,
  creado_por int references empleados(id),
  creado_en timestamptz not null default now()
);
create index turnos_taller_fecha_idx on turnos(sucursal_taller_id, fecha);
create index turnos_estado_idx on turnos(estado);
create index turnos_vehiculo_idx on turnos(vehiculo_id);
create index turnos_cliente_idx on turnos(cliente_id);
create index turnos_origen_idx on turnos(sucursal_origen_id);
create index turnos_servicio_idx on turnos(servicio_id);
create index turnos_creado_por_idx on turnos(creado_por);

create table eventos_turno (
  id int generated by default as identity primary key,
  turno_id int not null references turnos(id) on delete cascade,
  estado text not null, detalle text,
  empleado_id int references empleados(id),
  creado_en timestamptz not null default now()
);
create index eventos_turno_idx on eventos_turno(turno_id, creado_en);
create index eventos_empleado_idx on eventos_turno(empleado_id);

create table ordenes_trabajo (
  id int generated by default as identity primary key,
  turno_id int not null unique references turnos(id) on delete cascade,
  km_ingreso int not null check (km_ingreso >= 0),
  combustible_nivel text not null check (combustible_nivel in ('reserva','1/4','1/2','3/4','lleno')),
  observaciones text, danos_visibles text,
  trabajos_solicitados text not null,
  estado text not null default 'pendiente' check (estado in ('pendiente','asignada','en_reparacion','espera_repuestos','terminada','cerrada')),
  km_egreso int, trabajos_realizados text,
  abierta_en timestamptz not null default now(),
  cerrada_en timestamptz
);
create index ordenes_estado_idx on ordenes_trabajo(estado);

create table asignaciones (
  id int generated by default as identity primary key,
  orden_id int not null unique references ordenes_trabajo(id) on delete cascade,
  mecanico_id int not null references mecanicos(id),
  minutos_estimados int not null check (minutos_estimados > 0),
  inicio_en timestamptz, fin_en timestamptz,
  motivo_demora text,
  creado_en timestamptz not null default now()
);
create index asignaciones_mecanico_idx on asignaciones(mecanico_id);

create table historial_service (
  id int generated by default as identity primary key,
  vehiculo_id int not null references vehiculos(id) on delete cascade,
  turno_id int references turnos(id) on delete set null,
  sucursal_id int references sucursales(id),
  fecha date not null, km int not null,
  servicio text not null, trabajos text
);
create index historial_vehiculo_idx on historial_service(vehiculo_id, fecha desc);
create index historial_turno_idx on historial_service(turno_id);
create index historial_sucursal_idx on historial_service(sucursal_id);

create table notificaciones (
  id int generated by default as identity primary key,
  tipo text not null check (tipo in ('estado','recordatorio_turno','recordatorio_service','encuesta')),
  turno_id int references turnos(id) on delete cascade,
  vehiculo_id int references vehiculos(id) on delete cascade,
  cliente_id int not null references clientes(id),
  sucursal_id int not null references sucursales(id),
  mensaje text not null,
  estado text not null default 'pendiente' check (estado in ('pendiente','enviada')),
  canal text check (canal in ('whatsapp','email')),
  clave text unique,  -- evita duplicar recordatorios automáticos
  programada_para date not null default current_date,
  enviada_en timestamptz,
  empleado_id int references empleados(id),
  creado_en timestamptz not null default now()
);
create index notificaciones_sucursal_idx on notificaciones(sucursal_id, estado);
create index notificaciones_turno_idx on notificaciones(turno_id);
create index notificaciones_vehiculo_idx on notificaciones(vehiculo_id);
create index notificaciones_cliente_idx on notificaciones(cliente_id);
create index notificaciones_empleado_idx on notificaciones(empleado_id);

create table encuestas (
  id int generated by default as identity primary key,
  turno_id int not null unique references turnos(id) on delete cascade,
  puntaje int not null check (puntaje between 1 and 5),
  comentario text,
  creado_en timestamptz not null default now()
);

create table tasaciones (
  id int generated by default as identity primary key,
  cliente_id int not null references clientes(id),
  sucursal_id int not null references sucursales(id),
  unidad_interes_id int references unidades(id) on delete set null,
  marca text not null, modelo text not null, anio int not null, km int not null,
  estado_general text not null check (estado_general in ('excelente','muy_bueno','bueno','regular')),
  comentarios text,
  fotos jsonb not null default '[]',
  estado text not null default 'pendiente' check (estado in ('pendiente','respondida')),
  valor_estimado numeric(14,2), respuesta text,
  respondida_por int references empleados(id), respondida_en timestamptz,
  creado_en timestamptz not null default now()
);
create index tasaciones_sucursal_idx on tasaciones(sucursal_id, estado);
create index tasaciones_cliente_idx on tasaciones(cliente_id);
create index tasaciones_unidad_idx on tasaciones(unidad_interes_id);
create index tasaciones_respondida_por_idx on tasaciones(respondida_por);

-- Extra 9: reservas con vencimiento a las 72 h
create table reservas_unidad (
  id int generated by default as identity primary key,
  unidad_id int not null references unidades(id) on delete cascade,
  vendedor_id int not null references empleados(id),
  cliente_nombre text not null, cliente_telefono text,
  vence_en timestamptz not null default now() + interval '72 hours',
  estado text not null default 'activa' check (estado in ('activa','vencida','cancelada','concretada')),
  creado_en timestamptz not null default now()
);
create unique index reserva_activa_unica on reservas_unidad(unidad_id) where estado = 'activa';
create index reservas_vendedor_idx on reservas_unidad(vendedor_id);

-- Extra 10: transferencias entre sucursales
create table transferencias_unidad (
  id int generated by default as identity primary key,
  unidad_id int not null references unidades(id) on delete cascade,
  origen_id int not null references sucursales(id),
  destino_id int not null references sucursales(id),
  solicitada_por int not null references empleados(id),
  motivo text,
  estado text not null default 'solicitada' check (estado in ('solicitada','aprobada','rechazada')),
  resuelta_por int references empleados(id), resuelta_en timestamptz,
  creado_en timestamptz not null default now(),
  check (origen_id <> destino_id)
);
create index transferencias_unidad_idx on transferencias_unidad(unidad_id);
create index transferencias_origen_idx on transferencias_unidad(origen_id);
create index transferencias_destino_idx on transferencias_unidad(destino_id);
create index transferencias_solicitada_idx on transferencias_unidad(solicitada_por);
create index transferencias_resuelta_idx on transferencias_unidad(resuelta_por);

create table auditoria (
  id bigint generated by default as identity primary key,
  empleado_id int references empleados(id) on delete set null,
  empleado_nombre text,
  accion text not null, entidad text not null, entidad_id text,
  detalle jsonb,
  creado_en timestamptz not null default now()
);
create index auditoria_fecha_idx on auditoria(creado_en desc);
create index auditoria_empleado_idx on auditoria(empleado_id);

create table intentos_acceso (
  id bigint generated by default as identity primary key,
  empleado_id int references empleados(id) on delete cascade,
  exitoso boolean not null,
  ip text,
  creado_en timestamptz not null default now()
);
create index intentos_empleado_idx on intentos_acceso(empleado_id, creado_en desc);

-- Límite de solicitudes por IP en formularios públicos
create table solicitudes_publicas (
  id bigint generated by default as identity primary key,
  ip_hash text not null, accion text not null,
  creado_en timestamptz not null default now()
);
create index solicitudes_ip_idx on solicitudes_publicas(ip_hash, accion, creado_en desc);
